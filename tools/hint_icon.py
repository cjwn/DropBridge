"""Q59b: rebuild the tray/exe ICOs with hand-hinted small-size frames.

The artwork supplied for the tray is thin line art: its 16/20/24 px frames were
generated by downscaling the 256 px master, which leaves every stroke at 30-60 %
alpha. On a taskbar that reads as a grey smudge (measured: the 16 px frame had
0 pixels with alpha >= 200). This script keeps the original 48/64/256 frames and
redraws 16/20/24/32 as crisp 1 px strokes on the pixel grid, using the same
monitor + phone motif.

    python tools/hint_icon.py                # both assets
    python tools/hint_icon.py --check        # only report frame statistics
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
ICONS = (ASSETS / "dropbridge.ico", ASSETS / "dropbridge-tray-white.ico")
HINTED = (16, 20, 24, 32)
KEEP = (48, 64, 256)
GRID = 16.0


def solid_colour(master: Image.Image) -> tuple[int, int, int, int]:
    """Average colour of the fully opaque pixels, so black stays black and white stays white."""
    px = master.load()
    total = [0, 0, 0]
    count = 0
    for y in range(master.height):
        for x in range(master.width):
            r, g, b, a = px[x, y]
            if a >= 250:
                total[0] += r
                total[1] += g
                total[2] += b
                count += 1
    if not count:
        return (0, 0, 0, 255)
    return (total[0] // count, total[1] // count, total[2] // count, 255)


def draw_glyph(size: int, colour: tuple[int, int, int, int]) -> Image.Image:
    """Monitor on the left, phone on the right, 1 px strokes, no anti-aliasing."""
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    k = size / GRID

    def q(v: float) -> int:
        return int(round(v * k))

    radius = max(1, q(1))

    # monitor: 1..8 x 2..7 in grid units
    d.rounded_rectangle([q(1), q(2), q(8), q(7)], radius=radius, outline=colour, width=1)
    # stand: neck + base
    d.line([q(4.5), q(7) + 1, q(4.5), q(8.6)], fill=colour, width=1)
    d.line([q(2.4), q(8.6) + 1, q(6.6), q(8.6) + 1], fill=colour, width=1)
    # phone: 10..14 x 5..13
    d.rounded_rectangle([q(10), q(5), q(14), q(13)], radius=radius, outline=colour, width=1)
    if size >= 20:
        # speaker / home slot near the bottom of the phone
        d.line([q(11), q(11.5), q(13), q(11.5)], fill=colour, width=1)
    return img


def rebuild(path: Path, write: bool) -> None:
    path = path.resolve()
    src = Image.open(path)
    sizes = sorted(src.info.get("sizes", []))
    src.size = (256, 256)
    src.load()
    master = src.convert("RGBA")
    colour = solid_colour(master)

    frames: list[Image.Image] = []
    report: list[str] = []
    for size in HINTED:
        frame = draw_glyph(size, colour)
        frames.append(frame)
        alpha = frame.getchannel("A").histogram()
        solid = sum(alpha[200:])
        report.append(f"  hinted {size:>3}px: solid={solid:4d} semi={sum(alpha[20:200]):4d}")
    for size in KEEP:
        if (size, size) not in sizes:
            continue
        src.size = (size, size)
        src.load()
        frames.append(src.convert("RGBA"))

    print(f"== {path.relative_to(ROOT)}  colour={colour}")
    print("\n".join(report))
    if write:
        # The 256 px master is the base image; Pillow only writes sizes <= base.
        master.save(path, format="ICO", sizes=[(f.width, f.height) for f in frames] + [(256, 256)],
                    append_images=frames)
        out = Image.open(path)
        print(f"  wrote {path.stat().st_size} bytes, sizes={sorted(out.info.get('sizes', []))}")


def main(argv: list[str]) -> int:
    write = "--check" not in argv
    for path in ICONS:
        if not path.exists():
            print(f"missing {path}")
            return 1
        rebuild(path, write)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
